-- 預設任務類型「缺陷」改叫「問題」
--
-- 「缺陷」是品管的行話，畫面上看到的人得先在腦袋裡翻譯一次才知道那是
-- 「東西壞了、有人要修」。routes/parameters.ts 的 DEFAULT_PARAMS 已經改成
-- 「問題」，但那份清單只在建立專案時寫入，既有專案不會跟著換，所以這裡補一次。
--
-- **key 一個字都不動。** 任務是靠 task.type = 'BUG' 指回來的，
-- 改 key 等於把既有任務指向不存在的值（見 0011_project_parameters.sql 的說明）。
-- 這支只改畫面上顯示的 name。
--
-- **一定要帶 name = '缺陷' 這個條件。** 有人可能已經自己把它改成
-- 「異常」「待修項目」之類的說法了 —— 那是使用者自己調過的東西，
-- 不是我們的預設值，不可以拿系統的新說法蓋掉。沒改過的才換。

UPDATE task_type SET name = '問題' WHERE key = 'BUG' AND name = '缺陷';
