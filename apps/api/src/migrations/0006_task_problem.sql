-- 任務的「目前遇到的問題」
--
-- 為什麼是獨立欄位而不是寫進描述裡：描述講的是「這件事要做什麼」，
-- 問題講的是「現在為什麼推不動」。混在同一段文字裡，畫面就沒辦法在清單、
-- 看板、關聯圖上標出「哪幾張正卡著」—— 而那是每天開會第一個要看的東西。
--
-- 跟系統算出來的「卡住」是兩回事：卡住是依任務關聯推出來的（上游還沒完成），
-- 沒有人打過任何字，上游一完成它自己就消失；這一欄是人自己寫下的，
-- 系統推不出來，也因此只有人能決定它什麼時候不見。
--
-- 解決了就設回 null：任務身上只放「現在」的狀態，不然畫面得再多一個
-- 「這個問題還算不算數」的旗標，而那種旗標沒有人會記得更新。
-- 歷史不會因此消失 —— 清空前的內容會一起寫進 activity 的 FIELD_CHANGE，
-- 那張表本來就是任務的時間軸，不必為了問題再開一張表。

ALTER TABLE task ADD COLUMN problem text
  -- 空字串與 null 都表示「沒有問題」的話，每個查詢都得寫兩次判斷，
  -- 而且遲早會有一邊漏掉。在資料庫擋掉空字串，
  -- 「有沒有問題」就永遠只有 problem IS NOT NULL 這一種寫法。
  CHECK (problem IS NULL OR btrim(problem) <> '');
