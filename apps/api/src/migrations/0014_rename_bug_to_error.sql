-- 任務種類 BUG 的名字：「問題」→「錯誤」
--
-- 這一種的名字換過三次，都是同一個理由 —— 名字擋在功能前面：
--   「缺陷」  品管的行話，看的人得先翻譯一次（0012 換掉）
--   「問題」  跟「對外詢問」撞在一起；而且任務身上本來就有一個
--             「目前遇到的問題」欄位，講的是「這張現在卡在哪」，
--             跟「有個東西壞了要修」是完全不同的兩件事
--   「錯誤」  現在這個
--
-- key 一直是 BUG，三次都沒有動過 —— 任務是靠 key 指回來的（task.type），
-- 改 key 等於把既有任務指向不存在的值。
--
-- 只換還叫「問題」的。有人可能已經自己在系統參數頁改成別的名字了，
-- 那是使用者的東西，不可以覆蓋。跑第二次就一列都不會動到。

UPDATE task_type
   SET name = '錯誤'
 WHERE key = 'BUG'
   AND name = '問題';
