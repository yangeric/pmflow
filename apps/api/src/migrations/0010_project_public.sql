-- 專案可以設成公開
--
-- 選專案那一頁的「加入其他專案」現在要搜尋才找得到（專案名稱常常寫著客戶名或
-- 標案名，預設攤開來等於誰都讀得到這個組織在做哪些案子）。但有些專案本來就
-- 希望大家看得到、自己走進來 —— 全公司的年度計畫、公用的維運看板那種。
--
-- 公開只影響**找不找得到**，不影響**進不進得去**：公開的專案一樣要建立者核准
-- 才會變成成員，也一樣看不到裡面的任務。這條線刻意分開，
-- 不然「公開」會變成一個按下去就外洩內容的開關。
--
-- 預設 false：既有的專案維持現況，要公開的人自己去開。

ALTER TABLE project ADD COLUMN is_public boolean NOT NULL DEFAULT false;
